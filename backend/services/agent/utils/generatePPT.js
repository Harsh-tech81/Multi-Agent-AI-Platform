import pptxgen from "pptxgenjs";

const COLORS = {
  primary: "2563EB",
  secondary: "0F172A",
  text: "334155",
  light: "F8FAFC",
  border: "E2E8F0",
  white: "FFFFFF",
  muted: "64748B",
};

export const generatePPT = async (data) => {
  const ppt = new pptxgen();
  // Implementation for generating PPT
  ppt.layout = "LAYOUT_WIDE";
  ppt.author = "Agent-Flow-AI";
  ppt.title = data.title || "Untitled Presentation";
  ppt.subject = data.title || "Generated by AI";
  ppt.company = "Agent-Flow-AI";
  ppt.theme = {
    headerFontFace: "Aptos",
    bodyFontFace: "Aptos",
  };

  addCover(ppt, data);
  data?.slides?.forEach((slide, idx) => {
    addContentSlide(
      ppt,
      slide.title,
      slide.points,
      idx + 1,
      data.slides.length,
    );
  });
  addThankYouSlide(ppt);
  return ppt;
};

const addCover = (ppt, data) => {
  const slide = ppt.addSlide();
  slide.background = { color: COLORS.primary };
  slide.addShape(ppt.ShapeType.rect, {
    x: 0,
    y: 0,
    w: 13.33,
    h: 0.18,
    fill: { color: "60A5FA" },
    line: { color: "60A5FA" },
  });

  slide.addText(data.title || "Untitled Presentation", {
    x: 0.7,
    y: 1.7,
    w: 12,
    h: 0.8,
    align: "center",
    color: COLORS.white,
    bold: true,
    fontSize: 28,
  });

  slide.addText(data.subtitle || "Untitled Presentation", {
    x: 1,
    y: 2.8,
    w: 11.5,
    h: 0.4,
    align: "center",
    color: "DBEAFE",
    fontSize: 15,
  });

  slide.addText("Generated By Agent-Flow-AI", {
    x: 0,
    y: 6.9,
    w: 13.33,
    h: 0.2,
    align: "center",
    color: "BFDBFE",
    fontSize: 10,
  });
};

const addContentSlide = (ppt, title, points, slideNumber, totalSlides) => {
  const slide = ppt.addSlide();
  slide.background = { color: COLORS.white };

  slide.addText(title || "Untitled Presentation", {
    x: 0.6,
    y: 0.35,
    w: 10,
    h: 0.4,
    color: COLORS.primary,
    bold: true,
    fontSize: 24,
  });

  slide.addShape(ppt.ShapeType.line, {
    x: 0.6,
    y: 0.85,
    w: 12,
    h: 0,
    line: { color: COLORS.border, width: 1.2 },
  });

  const visiblePoints = points.slice(0, 6);
  visiblePoints.forEach((point, index) => {
    const y = 1.2 + index * 0.75;
    slide.addShape(ppt.ShapeType.roundRect, {
      x: 0.7,
      y: y,
      w: 12,
      h: 0.58,
      line: { color: COLORS.border },
      fill: { color: index % 2 ? "F8FAFC" : "EFF6FF" },
      radius: 0.08,
    });
    slide.addShape(ppt.ShapeType.ellipse, {
      x: 0.92,
      y: y + 0.18,
      w: 0.12,
      h: 0.12,
      line: { color: COLORS.primary },
      fill: { color: COLORS.primary },
    });
    slide.addText(point, {
      x: 1.2,
      y: y + 0.08,
      w: 11,
      h: 0.35,
      color: COLORS.text,
      fontSize: 15,
      fit: "shrink",
    });
  });

  slide.addText(`${slideNumber}/${totalSlides}`, {
    x: 12.1,
    y: 6.9,
    w: 0.8,
    h: 0.2,
    align: "right",
    color: COLORS.muted,
    fontSize: 10,
  });

  slide.addText("Agent-Flow-AI", {
    x: 0.6,
    y: 6.9,
    w: 2,
    h: 0.2,
    color: COLORS.muted,
    fontSize: 10,
  });
};

const addThankYouSlide = (ppt) => {
  const slide = ppt.addSlide();
  slide.background = { color: COLORS.secondary };

  slide.addText("Thank You!", {
    x: 0,
    y: 2.2,
    w: 13.33,
    h: 0.8,
    color: COLORS.white,
    fontSize: 34,
    align: "center",
    bold: true,
  });

  slide.addText("Generated By Agent-Flow-AI", {
    x: 0,
    y: 6.9,
    w: 13.33,
    h: 0.2,
    align: "center",
    color: "94A3B8",
    fontSize: 10,
  });
};
